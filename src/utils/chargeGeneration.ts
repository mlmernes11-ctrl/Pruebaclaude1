// =====================================================================
// Generación automática de cargos
// ---------------------------------------------------------------------
// Cada mes crea los cargos de los contratos activos (alquiler, y expensas y servicios
// si la propiedad los tiene), y actualiza las impagas si cambia un monto.
// =====================================================================

import { Charge, ChargeConcept, Contract, Currency, Property } from '../types';
import { addMonthsToPeriod, currentPeriod, periodToDueDate, toISODate } from './format';
import { generateId } from './id';
import { ChargePaymentInfo } from './ledger';

// Conceptos que se pueden liquidar, en el orden en que se muestran.
const CHARGE_CONCEPTS: ChargeConcept[] = ['alquiler', 'expensas', 'servicios'];

// Clave para saber si ya existe el cargo de un contrato, concepto y mes.
function chargeKey(contractId: string, concept: ChargeConcept, period: string) {
  return `${contractId}|${concept}|${period}`;
}

// Cuánto y en qué moneda se liquida un concepto según el contrato y la propiedad.
export function expectedCharge(
  contract: Contract,
  property: Property | undefined,
  concept: ChargeConcept,
): { amount: number; currency: Currency } | undefined {
  if (concept === 'alquiler') return { amount: contract.rentAmount, currency: contract.currency };
  const amount = concept === 'expensas' ? property?.expensasAmount : property?.serviciosAmount;
  return amount && amount > 0 ? { amount, currency: 'ARS' } : undefined;
}

// El primer vencimiento no puede caer antes de que empiece el contrato.
function dueDateFor(contract: Contract, period: string): string {
  const due = periodToDueDate(period, contract.paymentDay);
  return due < contract.startDate ? contract.startDate : due;
}

// Los meses se generan desde el inicio del contrato o desde el día en que se cargó en la app (lo
// que sea más tarde), así cargar un contrato viejo no crea años de deuda de golpe.
function firstBillablePeriod(contract: Contract): string {
  const startPeriod = contract.startDate.slice(0, 7);
  const fromPeriod =
    contract.billingStartPeriod ?? toISODate(new Date(contract.createdAt)).slice(0, 7);
  return startPeriod > fromPeriod ? startPeriod : fromPeriod;
}

// ── Generación mensual ────────────────────────────────────────────────

// Los cargos que faltan crear, desde el primer mes a cargar hasta este mes.
export function buildMissingCharges(
  contracts: Contract[],
  properties: Property[],
  charges: Charge[],
): Charge[] {
  const thisPeriod = currentPeriod();
  const existing = new Set(charges.map((c) => chargeKey(c.contractId, c.concept, c.period)));
  const now = new Date().toISOString();
  const missing: Charge[] = [];

  contracts
    .filter((contract) => contract.status === 'activo')
    .forEach((contract) => {
      const property = properties.find((p) => p.id === contract.propertyId);
      const endPeriod = contract.endDate.slice(0, 7) < thisPeriod ? contract.endDate.slice(0, 7) : thisPeriod;
      for (
        let period = firstBillablePeriod(contract);
        period <= endPeriod;
        period = addMonthsToPeriod(period, 1)
      ) {
        CHARGE_CONCEPTS.forEach((concept) => {
          const expected = expectedCharge(contract, property, concept);
          if (!expected || existing.has(chargeKey(contract.id, concept, period))) return;
          missing.push({
            id: generateId(),
            contractId: contract.id,
            concept,
            period,
            amount: expected.amount,
            currency: expected.currency,
            dueDate: dueDateFor(contract, period),
            autoGenerated: true,
            createdAt: now,
          });
        });
      }
    });

  return missing;
}

// ── Actualización de montos ───────────────────────────────────────────

// Si se corrige el alquiler o las expensas, los cargos automáticos impagos de este mes
// en adelante toman el valor nuevo; las pasadas o pagadas en parte quedan como estaban.
export function syncUnpaidAutoCharges(
  charges: Charge[],
  contracts: Contract[],
  properties: Property[],
  ledger: Map<string, ChargePaymentInfo>,
  contractIds: Set<string>,
): Charge[] {
  const thisPeriod = currentPeriod();
  return charges.map((charge) => {
    if (
      !charge.autoGenerated ||
      charge.voided ||
      charge.period < thisPeriod ||
      !contractIds.has(charge.contractId) ||
      (ledger.get(charge.id)?.paid ?? 0) > 0
    ) {
      return charge;
    }
    const contract = contracts.find((c) => c.id === charge.contractId);
    if (!contract) return charge;
    const property = properties.find((p) => p.id === contract.propertyId);
    const expected = expectedCharge(contract, property, charge.concept);
    if (!expected) return { ...charge, voided: true };
    return {
      ...charge,
      amount: expected.amount,
      currency: expected.currency,
      dueDate: dueDateFor(contract, charge.period),
    };
  });
}
