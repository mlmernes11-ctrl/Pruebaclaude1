export type Currency = 'USD' | 'ARS';

export type MoneyTotals = Record<Currency, number>;

export type PropertyType =
  | 'apartamento'
  | 'casa'
  | 'local'
  | 'oficina'
  | 'terreno'
  | 'otro';

export type PropertyStatus = 'disponible' | 'alquilada' | 'mantenimiento';

export interface Property {
  id: string;
  title: string;
  address: string;
  type: PropertyType;
  rooms?: number;
  bathrooms?: number;
  area?: number;
  rentAmount: number;
  rentCurrency: Currency;
  // Expensas and servicios are always billed in pesos.
  expensasAmount?: number;
  serviciosAmount?: number;
  status: PropertyStatus;
  notes?: string;
  createdAt: string;
}

export interface Tenant {
  id: string;
  name: string;
  document?: string;
  email?: string;
  phone?: string;
  notes?: string;
  createdAt: string;
}

export type ContractStatus = 'activo' | 'finalizado' | 'cancelado';

export interface Contract {
  id: string;
  propertyId: string;
  tenantId: string;
  startDate: string;
  endDate: string;
  rentAmount: number;
  currency: Currency;
  depositAmount?: number;
  paymentDay: number;
  // First month the app bills automatically; set for contracts loaded before auto-billing.
  billingStartPeriod?: string;
  status: ContractStatus;
  notes?: string;
  createdAt: string;
}

export type ChargeStatus = 'pagado' | 'pendiente' | 'vencido';

export type ChargeConcept = 'alquiler' | 'expensas' | 'servicios';

// What the tenant owes for one concept and month ("cuota").
export interface Charge {
  id: string;
  contractId: string;
  concept: ChargeConcept;
  period: string;
  amount: number;
  currency: Currency;
  dueDate: string;
  autoGenerated?: boolean;
  // Voided charges stay stored so monthly generation does not recreate them.
  voided?: boolean;
  notes?: string;
  createdAt: string;
}

export interface PaymentAllocation {
  chargeId: string;
  amount: number;
}

// Money actually received ("cobro"), applied to one or more charges of the same concept.
export interface Payment {
  id: string;
  contractId: string;
  concept: ChargeConcept;
  date: string;
  amount: number;
  currency: Currency;
  method?: string;
  // Pesos per dollar used when a dollar payment was settled.
  exchangeRate?: number;
  allocations: PaymentAllocation[];
  notes?: string;
  createdAt: string;
}
