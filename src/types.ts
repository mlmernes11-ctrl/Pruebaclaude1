// =====================================================================
// Tipos de datos
// ---------------------------------------------------------------------
// La forma de cada cosa que guarda la app: propiedad, inquilino, contrato, cargo y pago.
// Los nombres en inglés coinciden con las columnas de la base (en la base van en snake_case).
// =====================================================================

// ── Monedas ───────────────────────────────────────────────────────────

export type Currency = 'USD' | 'ARS';

export type MoneyTotals = Record<Currency, number>;

// ── Propiedades ───────────────────────────────────────────────────────

export type PropertyType =
  | 'apartamento'
  | 'casa'
  | 'local'
  | 'oficina'
  | 'terreno'
  | 'otro';

export type PropertyStatus = 'disponible' | 'alquilada' | 'mantenimiento';

export interface Property {
  id: string;
  title: string;
  address: string;
  neighborhood?: string;
  type: PropertyType;
  rooms?: number;
  bathrooms?: number;
  area?: number;
  // Precio publicado (opcional): solo de referencia. Lo que se cobra es el alquiler del contrato.
  rentAmount?: number;
  rentCurrency: Currency;
  // Las expensas y los servicios siempre se liquidan en pesos.
  expensasAmount?: number;
  serviciosAmount?: number;
  status: PropertyStatus;
  notes?: string;
  createdAt: string;
}

// ── Inquilinos ────────────────────────────────────────────────────────

export interface Tenant {
  id: string;
  name: string;
  document?: string;
  email?: string;
  phone?: string;
  notes?: string;
  createdAt: string;
}

// ── Contratos ─────────────────────────────────────────────────────────

export type ContractStatus = 'activo' | 'finalizado' | 'cancelado';

// Cómo se ajusta el alquiler: por IPC (INDEC), por ICL (BCRA) o un porcentaje fijo.
export type AdjustmentIndex = 'ipc' | 'icl' | 'fijo';

export interface Contract {
  id: string;
  propertyId: string;
  tenantId: string;
  startDate: string;
  endDate: string;
  rentAmount: number;
  currency: Currency;
  depositAmount?: number;
  paymentDay: number;
  // Primer mes que la app liquida sola (AAAA-MM).
  billingStartPeriod?: string;
  // Ajuste del alquiler cada tantos meses desde el inicio. Lo aplica el servidor: actualiza
  // rentAmount y anota en lastAdjustedPeriod el mes del último ajuste (AAAA-MM).
  adjustmentIndex?: AdjustmentIndex;
  adjustmentMonths?: number;
  adjustmentPercent?: number;
  lastAdjustedPeriod?: string;
  status: ContractStatus;
  notes?: string;
  createdAt: string;
}

// ── Cargos ─────────────────────────────────────────────────────

export type ChargeStatus = 'pagado' | 'pendiente' | 'vencido';

export type ChargeConcept = 'alquiler' | 'expensas' | 'servicios';

// Cargo: lo que el inquilino debe por un concepto y un mes.
export interface Charge {
  id: string;
  contractId: string;
  concept: ChargeConcept;
  period: string;
  amount: number;
  currency: Currency;
  dueDate: string;
  autoGenerated?: boolean;
  // Anulada: queda guardada para que la generación mensual no la vuelva a crear.
  voided?: boolean;
  // Revisado en "Expensas y servicios" (con un importe nuevo o manteniendo el anterior).
  confirmed?: boolean;
  notes?: string;
  createdAt: string;
}

// ── Cobros ─────────────────────────────────────────────────────────────

// Cuánto de un cobro se aplicó a un cargo.
export interface PaymentAllocation {
  chargeId: string;
  amount: number;
}

// Cobro recibido, aplicado a una o más cargos del mismo concepto.
export interface Payment {
  id: string;
  contractId: string;
  concept: ChargeConcept;
  date: string;
  amount: number;
  currency: Currency;
  method?: string;
  // Cotización usada (pesos por dólar), si hubo dólares de por medio.
  exchangeRate?: number;
  // Si se pagó en otra moneda (por ejemplo pesos por un alquiler en dólares): lo que se recibió
  // de verdad y de qué cotización salió. "amount" sigue siendo lo que se descuenta de la deuda.
  paidAmount?: number;
  paidCurrency?: Currency;
  rateSource?: 'blue' | 'oficial' | 'bolsa' | 'manual';
  allocations: PaymentAllocation[];
  notes?: string;
  // Los cobros cargados juntos en un recibo (por ejemplo alquiler + expensas) comparten este valor.
  receiptId?: string;
  createdAt: string;
}

// ── Todo junto ────────────────────────────────────────────────────────

// Todos los datos de la app juntos (lo que se guarda en Supabase o, en modo demo, en el celular).
export interface AppData {
  properties: Property[];
  tenants: Tenant[];
  contracts: Contract[];
  charges: Charge[];
  payments: Payment[];
}
