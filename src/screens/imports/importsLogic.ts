// =====================================================================
// Actualizar importes: datos y reglas
// ---------------------------------------------------------------------
// Una fila por contrato vigente con su cargo del mes (expensas, servicios o alquiler), el importe
// del mes anterior y si ya se revisó. Y qué hacer al guardar:
//   - Cargo sin cobros: toma el importe nuevo.
//   - Cargo con cobros: no se toca; si el importe nuevo es mayor, la diferencia va en un cargo
//     aparte ("Ajuste de expensas"); si es menor, baja hasta lo ya cobrado como mínimo.
//   - Si es el mes en curso, el importe queda como base para los meses siguientes (en la
//     propiedad para expensas y servicios, en el contrato para el alquiler).
// Las expensas y los servicios cambian casi todos los meses: los que no se revisaron cuentan
// como pendientes. El alquiler solo cambia con un ajuste, así que nunca queda "pendiente".
// =====================================================================

import { Charge, ChargeConcept, Contract, Property, Tenant } from '../../types';
import { addMonthsToPeriod, currentPeriod, todayISO } from '../../utils/format';
import { ChargeView, roundMoney } from '../../utils/ledger';

export interface ImportRow {
  view: ChargeView;
  contract: Contract;
  property?: Property;
  tenant?: Tenant;
  // Importe del mismo concepto el mes anterior (si hubo cargo), con sus ajustes.
  previous?: number;
  // Cargos aparte del mismo mes y concepto ("Ajuste de expensas"), que se suman al importe.
  extra: number;
  // Importe total del mes: el cargo más sus ajustes.
  total: number;
  // El alquiler de un contrato con ajuste automático (IPC, ICL o %) no se edita acá.
  automatic: boolean;
}

// Los cargos automáticos de un concepto y mes, uno por contrato vigente.
export function importRows(
  concept: ChargeConcept,
  period: string,
  chargeViews: ChargeView[],
  contracts: Contract[],
  properties: Property[],
  tenants: Tenant[],
): ImportRow[] {
  const previousPeriod = addMonthsToPeriod(period, -1);
  // Suma de los cargos a mano (ajustes) de un contrato, concepto y mes.
  const extraOf = (contractId: string, p: string) =>
    roundMoney(
      chargeViews
        .filter((v) => v.charge.contractId === contractId && v.charge.concept === concept && v.charge.period === p && !v.charge.autoGenerated)
        .reduce((sum, v) => sum + v.charge.amount, 0),
    );
  return chargeViews
    .filter((v) => v.charge.concept === concept && v.charge.period === period && v.charge.autoGenerated)
    .flatMap((view) => {
      const contract = contracts.find((c) => c.id === view.charge.contractId);
      if (!contract) return [];
      const property = properties.find((p) => p.id === contract.propertyId);
      const previousCharge = chargeViews.find(
        (v) =>
          v.charge.contractId === contract.id &&
          v.charge.concept === concept &&
          v.charge.period === previousPeriod &&
          v.charge.autoGenerated,
      )?.charge;
      const extra = extraOf(contract.id, period);
      return [
        {
          view,
          contract,
          property,
          tenant: tenants.find((t) => t.id === contract.tenantId),
          previous: previousCharge ? roundMoney(previousCharge.amount + extraOf(contract.id, previousPeriod)) : undefined,
          extra,
          total: roundMoney(view.charge.amount + extra),
          automatic: concept === 'alquiler' && Boolean(contract.adjustmentIndex),
        },
      ];
    })
    .sort((a, b) => (a.property?.title ?? '').localeCompare(b.property?.title ?? '', 'es', { numeric: true }));
}

// Expensas o servicios del mes sin revisar (lo que cuenta el aviso del Inicio y el Menú).
export const isPendingImport = (row: ImportRow) => row.view.charge.concept !== 'alquiler' && !row.view.charge.confirmed;

export function pendingImportsCount(chargeViews: ChargeView[], period = currentPeriod()): number {
  return chargeViews.filter(
    (v) =>
      v.charge.period === period &&
      v.charge.autoGenerated &&
      v.charge.concept !== 'alquiler' &&
      !v.charge.confirmed,
  ).length;
}

// Nombre del cargo aparte para la diferencia: "Ajuste de expensas".
const ADJUSTMENT_NOTE: Record<ChargeConcept, string> = {
  alquiler: 'Ajuste de alquiler',
  expensas: 'Ajuste de expensas',
  servicios: 'Ajuste de servicios',
};

// Lo que hay que hacer con un cargo al guardar un importe (nuevo o el mismo).
export interface ImportChange {
  // Cambios en el cargo del mes.
  charge: Partial<Charge>;
  // Cargo aparte por la diferencia, si el cargo ya tenía cobros y el importe subió.
  extra?: Omit<Charge, 'id' | 'createdAt'>;
}

// El importe nuevo se compara con el total del mes (cargo + ajustes que ya tenga).
export function planImportChange(row: ImportRow, newAmount: number): ImportChange {
  const { charge, paid } = row.view;
  const diff = roundMoney(newAmount - row.total);
  if (diff === 0) return { charge: { confirmed: true } };
  // Sin cobros: se corrige el cargo mismo (si queda en positivo).
  if (paid <= 0) {
    const amount = roundMoney(charge.amount + diff);
    return { charge: amount > 0 ? { amount, confirmed: true } : { confirmed: true } };
  }
  // Con cobros y el importe sube: la diferencia va en un cargo aparte, que vence hoy como muy
  // temprano (nunca nace vencido).
  if (diff > 0) {
    const today = todayISO();
    return {
      charge: { confirmed: true },
      extra: {
        contractId: charge.contractId,
        concept: charge.concept,
        period: charge.period,
        amount: diff,
        currency: charge.currency,
        dueDate: charge.dueDate > today ? charge.dueDate : today,
        notes: ADJUSTMENT_NOTE[charge.concept],
      },
    };
  }
  // Con cobros y el importe baja: baja hasta lo ya cobrado como mínimo.
  return { charge: { amount: Math.max(roundMoney(charge.amount + diff), paid), confirmed: true } };
}

// "+9,0 %" o "−3,5 %" entre el importe anterior y el nuevo.
export function percentChange(previous: number | undefined, next: number): string | undefined {
  if (!previous || previous <= 0 || next === previous) return undefined;
  const pct = ((next - previous) / previous) * 100;
  return `${pct > 0 ? '+' : '−'}${Math.abs(pct).toFixed(1).replace('.', ',')} %`;
}
