// =====================================================================
// Lectura y guardado en Supabase
// ---------------------------------------------------------------------
// Convierte los datos de la app al formato de las tablas (y al revés), los descarga al abrir
// y envía solo lo que cambió cada vez que se guarda.
// =====================================================================

import { AppData } from '../types';
import { connectionErrorMessage } from '../utils/platform';
import { Database } from './database.types';
import { supabase } from './supabase';

type Collection = keyof AppData;

// ── Tablas y columnas ─────────────────────────────────────────────────

// Primero las tablas "padre" y después las "hijas", para que las relaciones existan al guardar (al borrar, al revés).
const ORDER: Collection[] = ['properties', 'tenants', 'contracts', 'charges', 'payments'];

// — Verificación contra la base (database.types.ts) —
// "rentAmount" → "rent_amount", pero hecho con tipos: lo comprueba el verificador antes de publicar.
type CamelToSnake<S extends string> = S extends `${infer Head}${infer Tail}`
  ? `${Head extends Uppercase<Head> ? (Head extends Lowercase<Head> ? Head : `_${Lowercase<Head>}`) : Head}${CamelToSnake<Tail>}`
  : S;
type DbRow<C extends Collection> = Database['public']['Tables'][C]['Row'];
type AppField<C extends Collection> = Extract<keyof AppData[C][number], string>;
// Campos de la app que tienen su columna en la base.
type DbField<C extends Collection> = {
  [K in AppField<C>]: CamelToSnake<K> extends keyof DbRow<C> ? K : never;
}[AppField<C>];

// Columnas de cada tabla, con el nombre que usa la app (en la base van en snake_case).
// Si acá se nombra un campo sin columna en la base, el verificador da error.
const COLUMNS = {
  properties: [
    'id', 'title', 'address', 'neighborhood', 'type', 'rooms', 'bathrooms', 'area', 'rentAmount', 'rentCurrency',
    'expensasAmount', 'serviciosAmount', 'status', 'notes', 'createdAt',
  ],
  tenants: ['id', 'name', 'document', 'email', 'phone', 'notes', 'createdAt'],
  contracts: [
    'id', 'propertyId', 'tenantId', 'startDate', 'endDate', 'rentAmount', 'currency', 'depositAmount', 'paymentDay',
    'billingStartPeriod', 'adjustmentIndex', 'adjustmentMonths', 'adjustmentPercent', 'lastAdjustedPeriod',
    'status', 'notes', 'createdAt',
  ],
  charges: [
    'id', 'contractId', 'concept', 'period', 'amount', 'currency', 'dueDate', 'autoGenerated', 'voided', 'notes', 'createdAt',
  ],
  payments: [
    'id', 'contractId', 'concept', 'date', 'amount', 'currency', 'method', 'exchangeRate', 'allocations', 'notes',
    'receiptId', 'paidAmount', 'paidCurrency', 'rateSource', 'createdAt',
  ],
} as const satisfies { [C in Collection]: readonly DbField<C>[] };

// Y al revés: si la base tiene una columna que la app no lee ni guarda (por ejemplo, una nueva
// que se olvidó agregar arriba), el verificador da error acá y dice cuál falta.
type MissingColumns<C extends Collection> = Exclude<
  keyof DbRow<C>,
  'user_id' | CamelToSnake<(typeof COLUMNS)[C][number]>
>;
type AssertNone<T extends never> = T;
export type AllColumnsCovered = AssertNone<
  | MissingColumns<'properties'>
  | MissingColumns<'tenants'>
  | MissingColumns<'contracts'>
  | MissingColumns<'charges'>
  | MissingColumns<'payments'>
>;

const columnsOf = (collection: Collection): readonly string[] => COLUMNS[collection];

// La base puede devolver los montos como texto; la app trabaja con números.
const NUMERIC = new Set([
  'rooms', 'bathrooms', 'area', 'rentAmount', 'expensasAmount', 'serviciosAmount', 'depositAmount', 'paymentDay',
  'amount', 'exchangeRate', 'paidAmount', 'adjustmentMonths', 'adjustmentPercent',
]);

// "rentAmount" → "rent_amount".
const toSnake = (key: string) => key.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

// ── Conversión app ↔ base ─────────────────────────────────────────────

// Registro de la app → fila de la tabla.
function toRow(collection: Collection, item: object): Record<string, unknown> {
  const source = item as Record<string, unknown>;
  const row: Record<string, unknown> = {};
  columnsOf(collection).forEach((key) => {
    const value = source[key];
    row[toSnake(key)] = value === undefined ? null : value;
  });
  // En la base estos sí/no son obligatorios (no pueden quedar vacíos).
  if (collection === 'charges') {
    row.auto_generated = Boolean(source.autoGenerated);
    row.voided = Boolean(source.voided);
  }
  return row;
}

// Fila de la tabla → registro de la app.
function fromRow<T>(collection: Collection, row: Record<string, unknown>): T {
  const item: Record<string, unknown> = {};
  columnsOf(collection).forEach((key) => {
    const value = row[toSnake(key)];
    if (value === null || value === undefined) return;
    if (NUMERIC.has(key)) item[key] = Number(value);
    else if (key === 'allocations') {
      item[key] = (value as { chargeId: string; amount: number }[]).map((a) => ({ chargeId: a.chargeId, amount: Number(a.amount) }));
    } else item[key] = value;
  });
  if (collection === 'payments' && !item.allocations) item.allocations = [];
  return item as T;
}

// ── Lectura ───────────────────────────────────────────────────────────

// El servidor nunca devuelve más de 1000 filas por pedido (y no avisa si cortó), así que cada
// tabla se pide de a tandas, ordenadas por id para que ninguna fila se repita ni se saltee.
const PAGE_SIZE = 1000;

async function loadAll(collection: Collection): Promise<Record<string, unknown>[]> {
  const rows: Record<string, unknown>[] = [];
  for (let from = 0; ; from += PAGE_SIZE) {
    const { data, error } = await supabase
      .from(collection)
      .select('*')
      .order('id')
      .range(from, from + PAGE_SIZE - 1);
    if (error) throw error;
    rows.push(...((data ?? []) as Record<string, unknown>[]));
    if (!data || data.length < PAGE_SIZE) return rows;
  }
}

// Descarga todas las tablas al abrir la app.
export async function loadRemoteData(): Promise<AppData> {
  const results = await Promise.all(ORDER.map(loadAll));
  const data = {} as AppData;
  results.forEach((rows, index) => {
    const collection = ORDER[index];
    (data as unknown as Record<Collection, unknown[]>)[collection] = rows.map((row) => fromRow(collection, row));
  });
  return data;
}

// ── Guardado ──────────────────────────────────────────────────────────

// Lo que hay que enviar: filas nuevas o cambiadas (upserts) y filas borradas (deletes).
export interface RemoteChanges {
  upserts: Partial<Record<Collection, object[]>>;
  deletes: Partial<Record<Collection, string[]>>;
}

// Qué cambió entre lo que tiene el servidor y lo que tiene la app ahora.
export function diffData(previous: AppData, next: AppData): RemoteChanges {
  const changes: RemoteChanges = { upserts: {}, deletes: {} };
  ORDER.forEach((collection) => {
    // Se comparan ya convertidos a filas de la base, así diferencias de formato no cuentan como cambios.
    const asRow = (item: object) => JSON.stringify(toRow(collection, item));
    const before = new Map((previous[collection] as { id: string }[]).map((item) => [item.id, asRow(item)]));
    const nextItems = next[collection] as { id: string }[];
    const nextIds = new Set(nextItems.map((item) => item.id));
    const upserts = nextItems.filter((item) => before.get(item.id) !== asRow(item));
    const deletes = [...before.keys()].filter((id) => !nextIds.has(id));
    if (upserts.length) changes.upserts[collection] = upserts;
    if (deletes.length) changes.deletes[collection] = deletes;
  });
  return changes;
}

// true si hay algo para enviar.
export function hasChanges(changes: RemoteChanges): boolean {
  return Object.keys(changes.upserts).length > 0 || Object.keys(changes.deletes).length > 0;
}

// Envía los cambios al servidor, tabla por tabla.
export async function pushChanges(changes: RemoteChanges): Promise<void> {
  for (const collection of ORDER) {
    const items = changes.upserts[collection];
    if (!items?.length) continue;
    const { error } = await supabase
      .from(collection)
      .upsert(items.map((item) => toRow(collection, item)), { onConflict: 'id' });
    if (error) throw error;
  }
  for (const collection of [...ORDER].reverse()) {
    const ids = changes.deletes[collection];
    if (!ids?.length) continue;
    const { error } = await supabase.from(collection).delete().in('id', ids);
    if (error) throw error;
  }
}

// ── Errores ───────────────────────────────────────────────────────────

// Mensaje claro cuando falla un pedido al servidor.
export function describeRemoteError(error: unknown): string {
  const message = (error as { message?: string })?.message ?? '';
  if (/fetch|network/i.test(message)) return connectionErrorMessage();
  return 'El servidor no pudo guardar los cambios. Intentá de nuevo en unos minutos.';
}

// El servidor rechazó un duplicado (por ejemplo, la misma liquidación del mes creada en otro celular).
export const isConflict = (error: unknown) => (error as { code?: string })?.code === '23505';
