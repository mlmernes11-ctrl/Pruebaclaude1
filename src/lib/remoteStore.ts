// =====================================================================
// Lectura y guardado en Supabase
// ---------------------------------------------------------------------
// Convierte los datos de la app al formato de las tablas (y al revés), los descarga al abrir
// y envía solo lo que cambió cada vez que se guarda. También le pide al servidor que haga lo
// automático de la cuenta (cargos del mes, ajustes y saldo a favor).
//
// En la app, cada cobro lleva su lista de repartos ("allocations"); en la base, los repartos
// viven en su propia tabla (payment_allocations). La conversión se hace acá.
// =====================================================================

import { AppData, Payment } from '../types';
import { connectionErrorMessage } from '../utils/platform';
import { Database } from './database.types';
import { supabase } from './supabase';

// ── Tablas ────────────────────────────────────────────────────────────

type Collection = keyof AppData;

// Un reparto como fila de la base: "cobro|cargo", cobro, cargo y monto.
interface AllocationRecord {
  id: string;
  paymentId: string;
  chargeId: string;
  amount: number;
}
type Table = Collection | 'payment_allocations';
type RemoteData = AppData & { payment_allocations: AllocationRecord[] };

// Primero las tablas "padre" y después las "hijas", para que las relaciones existan al guardar (al borrar, al revés).
const ORDER: Table[] = ['properties', 'tenants', 'contracts', 'charges', 'payments', 'payment_allocations'];

// ── Columnas (verificadas contra database.types.ts) ───────────────────

// "rentAmount" → "rent_amount", pero hecho con tipos: lo comprueba el verificador antes de publicar.
type CamelToSnake<S extends string> = S extends `${infer Head}${infer Tail}`
  ? `${Head extends Uppercase<Head> ? (Head extends Lowercase<Head> ? Head : `_${Lowercase<Head>}`) : Head}${CamelToSnake<Tail>}`
  : S;
type DbRow<T extends Table> = Database['public']['Tables'][T]['Row'];
type AppRecord<T extends Table> = T extends Collection ? AppData[T][number] : AllocationRecord;
type AppField<T extends Table> = Extract<keyof AppRecord<T>, string>;
// Campos de la app que tienen su columna en la base.
type DbField<T extends Table> = {
  [K in AppField<T>]: CamelToSnake<K> extends keyof DbRow<T> ? K : never;
}[AppField<T>];

// Columnas de cada tabla, con el nombre que usa la app (en la base van en snake_case).
// Si acá se nombra un campo sin columna en la base, el verificador da error.
const COLUMNS = {
  properties: [
    'id', 'title', 'address', 'neighborhood', 'type', 'rooms', 'bathrooms', 'area', 'rentAmount', 'rentCurrency',
    'expensasAmount', 'serviciosAmount', 'status', 'notes', 'createdAt',
  ],
  tenants: ['id', 'name', 'document', 'email', 'phone', 'notes', 'createdAt'],
  contracts: [
    'id', 'propertyId', 'tenantId', 'startDate', 'endDate', 'rentAmount', 'currency', 'depositAmount', 'paymentDay',
    'billingStartPeriod', 'adjustmentIndex', 'adjustmentMonths', 'adjustmentPercent', 'lastAdjustedPeriod',
    'status', 'notes', 'createdAt',
  ],
  charges: [
    'id', 'contractId', 'concept', 'period', 'amount', 'currency', 'dueDate', 'autoGenerated', 'voided', 'notes', 'createdAt',
  ],
  payments: [
    'id', 'contractId', 'concept', 'date', 'amount', 'currency', 'method', 'exchangeRate', 'notes',
    'receiptId', 'paidAmount', 'paidCurrency', 'rateSource', 'createdAt',
  ],
  payment_allocations: ['id', 'paymentId', 'chargeId', 'amount'],
} as const satisfies { [T in Table]: readonly DbField<T>[] };

// Y al revés: si la base tiene una columna que la app no lee ni guarda (por ejemplo, una nueva
// que se olvidó agregar arriba), el verificador da error acá y dice cuál falta.
type MissingColumns<T extends Table> = Exclude<keyof DbRow<T>, 'user_id' | CamelToSnake<(typeof COLUMNS)[T][number]>>;
type AssertNone<T extends never> = T;
export type AllColumnsCovered = AssertNone<{ [T in Table]: MissingColumns<T> }[Table]>;

const columnsOf = (table: Table): readonly string[] => COLUMNS[table];

// La base puede devolver los montos como texto; la app trabaja con números.
const NUMERIC = new Set([
  'rooms', 'bathrooms', 'area', 'rentAmount', 'expensasAmount', 'serviciosAmount', 'depositAmount', 'paymentDay',
  'amount', 'exchangeRate', 'paidAmount', 'adjustmentMonths', 'adjustmentPercent',
]);

// "rentAmount" → "rent_amount".
const toSnake = (key: string) => key.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

// ── Conversión app ↔ base ─────────────────────────────────────────────

// Registro de la app → fila de la tabla.
function toRow(table: Table, item: object): Record<string, unknown> {
  const source = item as Record<string, unknown>;
  const row: Record<string, unknown> = {};
  columnsOf(table).forEach((key) => {
    const value = source[key];
    row[toSnake(key)] = value === undefined ? null : value;
  });
  // En la base estos sí/no son obligatorios (no pueden quedar vacíos).
  if (table === 'charges') {
    row.auto_generated = Boolean(source.autoGenerated);
    row.voided = Boolean(source.voided);
  }
  return row;
}

// Fila de la tabla → registro de la app.
function fromRow(table: Table, row: Record<string, unknown>): Record<string, unknown> {
  const item: Record<string, unknown> = {};
  columnsOf(table).forEach((key) => {
    const value = row[toSnake(key)];
    if (value === null || value === undefined) return;
    item[key] = NUMERIC.has(key) ? Number(value) : value;
  });
  return item;
}

// Los repartos de cada cobro, como filas de payment_allocations.
const allocationId = (paymentId: string, chargeId: string) => `${paymentId}|${chargeId}`;

function withAllocationRows(data: AppData): RemoteData {
  return {
    ...data,
    payment_allocations: data.payments.flatMap((p) =>
      p.allocations.map((a) => ({ id: allocationId(p.id, a.chargeId), paymentId: p.id, chargeId: a.chargeId, amount: a.amount })),
    ),
  };
}

// ── Lectura ───────────────────────────────────────────────────────────

// El servidor nunca devuelve más de 1000 filas por pedido (y no avisa si cortó), así que cada
// tabla se pide de a tandas, ordenadas por id para que ninguna fila se repita ni se saltee.
const PAGE_SIZE = 1000;

async function loadAll(table: Table): Promise<Record<string, unknown>[]> {
  const rows: Record<string, unknown>[] = [];
  for (let from = 0; ; from += PAGE_SIZE) {
    const { data, error } = await supabase
      .from(table)
      .select('*')
      .order('id')
      .range(from, from + PAGE_SIZE - 1);
    if (error) throw error;
    rows.push(...((data ?? []) as Record<string, unknown>[]));
    if (!data || data.length < PAGE_SIZE) return rows;
  }
}

// Descarga todas las tablas y arma los datos de la app (cada cobro con sus repartos).
export async function loadRemoteData(): Promise<AppData> {
  const results = await Promise.all(ORDER.map(loadAll));
  const byTable = Object.fromEntries(
    ORDER.map((table, index) => [table, results[index].map((row) => fromRow(table, row))]),
  ) as unknown as RemoteData;

  const allocationsByPayment = new Map<string, { chargeId: string; amount: number }[]>();
  byTable.payment_allocations.forEach((a) => {
    const list = allocationsByPayment.get(a.paymentId) ?? [];
    list.push({ chargeId: a.chargeId, amount: a.amount });
    allocationsByPayment.set(a.paymentId, list);
  });
  const payments: Payment[] = byTable.payments.map((p) => ({ ...p, allocations: allocationsByPayment.get(p.id) ?? [] }));

  return {
    properties: byTable.properties,
    tenants: byTable.tenants,
    contracts: byTable.contracts,
    charges: byTable.charges,
    payments,
  };
}

// ── Guardado ──────────────────────────────────────────────────────────

// Lo que hay que enviar: filas nuevas o cambiadas (upserts) y filas borradas (deletes).
export interface RemoteChanges {
  upserts: Partial<Record<Table, object[]>>;
  deletes: Partial<Record<Table, string[]>>;
}

// Qué cambió entre lo que tiene el servidor y lo que tiene la app ahora.
export function diffData(previousData: AppData, nextData: AppData): RemoteChanges {
  const previous = withAllocationRows(previousData);
  const next = withAllocationRows(nextData);
  const changes: RemoteChanges = { upserts: {}, deletes: {} };
  ORDER.forEach((table) => {
    // Se comparan ya convertidos a filas de la base, así diferencias de formato no cuentan como cambios.
    const asRow = (item: object) => JSON.stringify(toRow(table, item));
    const before = new Map((previous[table] as { id: string }[]).map((item) => [item.id, asRow(item)]));
    const nextItems = next[table] as { id: string }[];
    const nextIds = new Set(nextItems.map((item) => item.id));
    const upserts = nextItems.filter((item) => before.get(item.id) !== asRow(item));
    const deletes = [...before.keys()].filter((id) => !nextIds.has(id));
    if (upserts.length) changes.upserts[table] = upserts;
    if (deletes.length) changes.deletes[table] = deletes;
  });
  return changes;
}

// true si hay algo para enviar.
export function hasChanges(changes: RemoteChanges): boolean {
  return Object.keys(changes.upserts).length > 0 || Object.keys(changes.deletes).length > 0;
}

// Envía los cambios al servidor, tabla por tabla.
export async function pushChanges(changes: RemoteChanges): Promise<void> {
  for (const table of ORDER) {
    const items = changes.upserts[table];
    if (!items?.length) continue;
    const { error } = await supabase.from(table).upsert(items.map((item) => toRow(table, item)), { onConflict: 'id' });
    if (error) throw error;
  }
  for (const table of [...ORDER].reverse()) {
    const ids = changes.deletes[table];
    if (!ids?.length) continue;
    const { error } = await supabase.from(table).delete().in('id', ids);
    if (error) throw error;
  }
}

// ── ¿Cambió algo? ─────────────────────────────────────────────────────

// Número de versión de la cuenta: sube solo con cada cambio en sus datos (lo mantiene la base).
// Es un pedido mínimo; si el número cambió, recién ahí se vuelve a bajar todo.
export async function readAccountVersion(): Promise<number> {
  const { data, error } = await supabase.from('account_versions').select('version').maybeSingle();
  if (error) throw error;
  return Number(data?.version ?? 0);
}

// ── Lo automático de la cuenta ────────────────────────────────────────

// El servidor crea los cargos del mes que falten, aplica los ajustes de alquiler y el saldo a
// favor. Devuelve cuántos cambios hizo (si hizo alguno, hay que volver a leer los datos).
export async function runAccountBilling(): Promise<number> {
  const { data, error } = await supabase.rpc('run_my_billing');
  if (error) throw error;
  return Number(data ?? 0);
}

// ── Errores ───────────────────────────────────────────────────────────

// Mensaje claro cuando falla un pedido al servidor.
export function describeRemoteError(error: unknown): string {
  const message = (error as { message?: string })?.message ?? '';
  if (/fetch|network/i.test(message)) return connectionErrorMessage();
  return 'El servidor no pudo guardar los cambios. Intentá de nuevo en unos minutos.';
}

// El servidor rechazó un duplicado (por ejemplo, el mismo cargo del mes creado dos veces).
export const isConflict = (error: unknown) => (error as { code?: string })?.code === '23505';
